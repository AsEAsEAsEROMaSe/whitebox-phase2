def _mm(a, b, level=_STRASSEN_L):
    """Штрассен–Віноград: 7 добутків замість 8 на кожному рівні.

    🔒 ПЛОМБА, ЯКУ ТРЕБА ТРИМАТИ: при `level=0` це ТОТОЖНО `fnp.matmul` ⟹
    вирок можна виносити ЛИШЕ на різниці, а не на абсолюті.
    Розміри мусять ділитись на 2 на кожному рівні — це забезпечує кратність
    обрізання `G = 2**_STRASSEN_L` у `predict`, тож падіння в щільний шлях тут
    є СТРАХОВКОЮ, а не робочим режимом.
    """
    if level <= 0 or a.shape[0] % 2 or a.shape[1] % 2 or b.shape[1] % 2:
        return fnp.matmul(a, b)
    m, k, n = a.shape[0] // 2, a.shape[1] // 2, b.shape[1] // 2
    A11, A12, A21, A22 = a[:m, :k], a[:m, k:], a[m:, :k], a[m:, k:]
    B11, B12, B21, B22 = b[:k, :n], b[:k, n:], b[k:, :n], b[k:, n:]
    M1 = _mm(A11 + A22, B11 + B22, level - 1)
    M2 = _mm(A21 + A22, B11, level - 1)
    M3 = _mm(A11, B12 - B22, level - 1)
    M4 = _mm(A22, B21 - B11, level - 1)
    M5 = _mm(A11 + A12, B22, level - 1)
    M6 = _mm(A21 - A11, B11 + B12, level - 1)
    M7 = _mm(A12 - A22, B21 + B22, level - 1)
    return fnp.block([[M1 + M4 - M5 + M7, M3 + M5],
                      [M2 + M4, M1 - M2 + M3 + M6]])


def _phi(x):
    return fnp.exp(-0.5 * x * x) * _INV_SQRT_2PI


def _Phi(x):
    """Φ(x) = ½(1+erf(x/√2)) без `erf`: A&S 7.1.26 на |x|, знак — через sign."""
    ax = fnp.abs(x) * _INV_SQRT_2
    t = 1.0 / (1.0 + _P * ax)
    poly = ((((_A5 * t + _A4) * t + _A3) * t + _A2) * t + _A1) * t
    er = 1.0 - poly * fnp.exp(-ax * ax)
    return 0.5 * (1.0 + fnp.sign(x) * er)



