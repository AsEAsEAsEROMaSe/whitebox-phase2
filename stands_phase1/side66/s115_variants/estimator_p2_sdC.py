def _shape_corr(cpm, s, t, Ph, ph, mn, depth_frac):
    """навчена поправка ФОРМИ: ŷ·s, спроєктована геть від напрямку сигналу."""
    n = s.shape[0]
    inv = 1.0 / s
    R = cpm * fnp.outer(inv, inv)
    R = R - fnp.diag(fnp.diagonal(R))
    Rs = R * R
    sc = _FEAT_N0 / n
    R2 = fnp.sum(Rs, axis=1) * sc
    R3 = fnp.sum(Rs * R, axis=1) * sc
    R4 = fnp.sum(Rs * Rs, axis=1) * sc
    A1 = fnp.sum(fnp.abs(R), axis=1) * sc
    lPR = fnp.log(fnp.maximum(R2 * R2 / fnp.maximum(R4, 1e-30), 1e-30))
    sn = s / fnp.mean(s)
    tp = t * ph
    hp = (t * t - 1.0) * ph
    y = (_FW[0] + _FW[1] * t + _FW[2] * Ph + _FW[3] * ph + _FW[4] * tp
         + _FW[5] * hp + _FW[6] * R2 + _FW[7] * R3 + _FW[8] * R4
         + _FW[9] * A1 + _FW[10] * lPR + _FW[11] * sn
         + _FW[12] * depth_frac
         + _FW[13] * (t * R2) + _FW[14] * (ph * R2) + _FW[15] * (hp * R2))
    corr = y * s
    g = mn / fnp.maximum(fnp.sqrt(fnp.sum(mn * mn)), 1e-30)
    return corr - fnp.sum(corr * g) * g


def _closure_parts(w_cut, ksig, width, kdeep=None):
    """`s_j = √Var(p_j)` для `p` шарів 1..ksig І `m` активацій шарів 1..ksig.

    Старт `m=0, C=I` — не припущення: вибілювання робить емпіричну коваріацію
    входу ТОЧНО одиничною. Парні моменти relu беруться рядом Мелера
    `E[f(X)g(Y)] = Σ ρᵏ/k!·c_k c_k` при K=2, а ДІАГОНАЛЬ вписується точною
    формулою (ρ=1 — саме там ряд збігається найгірше)."""
    m = fnp.zeros(width, dtype=fnp.float32)
    # 🆕 С89: тег симетрії. `C` симетрична за побудовою на КОЖНОМУ кроці, але
    #    flopscope цього не знає і бере повний тариф. Тег коштує 458,751 флопів
    #    на шар і повертає 16.7e6 — окупність 36×.
    C = flops.as_symmetric(fnp.eye(width, dtype=fnp.float32), symmetry=(0, 1))
    out = []
    mo = []
    qo = []
    po = []
    # 🔑 ОПОРИ ДЛЯ ЛОКАЛЬНОЇ ПОПРАВКИ ДО `q` (sub93): `s²φ(t)` і `s²tφ(t)`.
    #    Зберігаємо готові добутки, а не `t`,`ph` окремо — менше елементних
    #    операцій у гарячому циклі `predict` і жодного зайвого стану.
    ao = []
    bo = []
    nit = ksig + 1 if kdeep is None else kdeep
    for i in range(nit):
        w = w_cut[i]
        # 🆕 С89: `wᵀCw` симетричний, але ДОВЕСТИ це flopscope може лише коли
        #    `C` НЕСЕ ТЕГ і згортка записана однією тризгорткою. Пара матмулів
        #    66,977,792 → einsum із тегом 50,298,752 (×0.751), пломба бітова.
        cp = fnp.einsum("ij,ia,jb->ab", C, w, w)
        if i > ksig:
            cp = cp * _KAPPA
        s = fnp.sqrt(fnp.maximum(fnp.diagonal(cp), 1e-20))
        if 1 <= i <= ksig:
            out.append(s)
        mp = fnp.matmul(m, w)
        t = mp / s
        ph = _phi(t)
        Ph = _Phi(t)
        if 1 <= i <= ksig:
            po.append(Ph)
            s2ph = (s * s) * ph
            ao.append(s2ph)
            bo.append(s2ph * t)
        m = mp * Ph + s * ph
        # 🆕 С114: поправка ФОРМИ — лише в ГЛИБОКІЙ гілці (i > ksig), щоб не
        #    зсунути опори λ-блоку (закон С100).
        if _LAM_FEAT != 0.0:
            m = m - _LAM_FEAT * _shape_corr(cp, s, t, Ph, ph, m,
                                            float(i) / float(nit))
        if i == nit - 1 and i > ksig:
            # 🔑 остання ітерація глибокої гілки: `C` більше нікому не потрібна
            #    ⟹ не рахуємо (мінус ~15 викликів `fnp` і купа елементних)
            break
        C = cp * fnp.outer(Ph, Ph) + (0.5 * (cp * cp)) * fnp.outer(ph / s, ph / s)
        d = (mp * mp + s * s) * Ph + (mp * s) * ph - m * m
        C = C + fnp.diag(d - fnp.diagonal(C))
        # 🆕 С89: тег рветься на `cp*outer(Ph,Ph)` (операнди не мають спільної
        #    групи симетрії) ⟹ відновлюємо ЩОШАРУ. `tag_once` дає лише −16.3e6,
        #    `tag_each` — −521.7e6 на 32 шарах.
        C = flops.as_symmetric(C, symmetry=(0, 1))
        if 1 <= i <= ksig:
            mo.append(m)
            qo.append(fnp.diagonal(C) + m * m)
    return out, mo, qo, po, m, ao, bo


class Estimator(BaseEstimator):
    def predict(self, mlp: MLP, budget: int) -> fnp.ndarray:
        width = mlp.width
        depth = len(mlp.weights)
        per_sample_full = 2.0 * depth * width * width
        rng = fnp.random.default_rng(_SEED)

        # ---------- 1) ПІЛОТ: хто ніколи не відкривається ----------
        zp = fnp.array(rng.standard_normal((_PILOT_PAIRS, width)).astype(fnp.float32))
        xp = fnp.concatenate([zp, -zp], axis=0)
        # 🆕 С110: обрізання ОКРУГЛЮЄТЬСЯ ВГОРУ до кратного `G = 2**_STRASSEN_L`,
        #    інакше рекурсія Штрассена падає в щільний шлях на непарних розмірах.
        #    Ціна: до G−1 зайвих нейронів на шар (~1% флопів) — і це нейрони, які
        #    пілот визнав мертвими, тож вони ЛИШЕ додають точності, не віднімають.
        #    Поріг береться сортуванням `mx` (4·n·log n = 8192 флопів на шар).
        _G = 1 << _STRASSEN_L
        alive = []
        a = xp
        for i in range(depth):
            h = fnp.matmul(a, mlp.weights[i])
            if i < depth - 1:
                mx = fnp.max(h, axis=0)
                keep = mx >= 0.0
                c = int(fnp.sum(keep.astype(mx.dtype)))
                t = min(width, ((c + _G - 1) // _G) * _G)
                if t > c:
                    keep = mx >= fnp.sort(mx)[width - t]
                alive.append(keep)
            a = fnp.maximum(h, 0.0)

        # ---------- 2) обрізані ваги ----------
        w_cut = []
        for i in range(depth):
            wi = mlp.weights[i]
            if i > 0:
                wi = wi[alive[i - 1], :]
            if i < depth - 1:
                wi = wi[:, alive[i]]
            w_cut.append(wi)
        per_sample_cut = 2.0 * sum(float(w.shape[0]) * float(w.shape[1]) for w in w_cut)

        # ---------- 3) основна вибірка крізь обрізану мережу ----------
        # 🚨 ПЛАНУВАЛЬНИК МУСИТЬ ЗНАТИ ПРО ЗНИЖКУ. `per_sample_cut` — це оцінка
        #    ЩІЛЬНОГО тарифу; зі Штрассеном семпл коштує ×_STRASSEN_COST, і якщо
        #    цього не врахувати, ми просто НЕДОВИТРАТИМО бюджет, а виграш = 0
        #    (рівно та пастка, що коштувала нам sub93: недобір 0.57% бюджету).
        per_sample_cut *= _STRASSEN_COST
        # 🚨 ФАЗА 2: замикання коштує ~19-23% ПІДЛОГИ (у фазі 1 було 6.1%),
        #    і планувальник його НЕ БАЧИВ — звідси перевитрата C/B 0.109.
        #    `_CLOSURE_COST` зміряно прямо: 4.16e10 / (16·1024³) = 2.42.
        used = (2.0 * _PILOT_PAIRS * per_sample_full
                + _CLOSURE_COST * depth * float(width) ** 3)
        left = _TARGET_UTIL * float(budget) - used
        n_pairs = max(_MIN_PAIRS, int(left / (2.0 * max(per_sample_cut, 1.0))))
        _H = max(1, _G // 2)
        n_pairs = (n_pairs // _H) * _H
        n_pairs -= n_pairs % _G          # M кожного матмула кратне G

        z = fnp.array(rng.standard_normal((n_pairs, width)).astype(fnp.float32))
        # 🔑 АНТИТЕТИКА: x = [z; −z] ⟹ xᵀx = zᵀz + (−z)ᵀ(−z) = 2·zᵀz ТОТОЖНО.
        #    Тож коваріація береться на ВДВІЧІ меншій матриці, а `x` тут узагалі
        #    не потрібен — його заміняє шар 0 нижче. Економія ≈1.9% усіх флопів.
        # 🆕 С89: `zᵀz` симетричний, і тут flopscope виводить це САМ — з
        #    ТОТОЖНОСТІ операндів, без тега. 355,008,512 → 178,197,632 (×0.502).
        cov = fnp.einsum("ia,ib->ab", z, z) / float(n_pairs)
        # 🆕 С89: ВИБІЛЮВАННЯ ХОЛЕЦЬКИМ ЗАМІСТЬ ZCA. Мета вибілювання — зробити
        #    емпіричну `cov` РІВНО одиничною, і `L^{-T}` робить це так само точно,
        #    як `cov^{-1/2}` (зміряно: 5.96e-07 проти 1.37e-06 у ZCA). Різниця
        #    між ними — поворот, а `z ~ N(0,I)` до поворотів інваріантний.
        #    eigh+matmul 184,550,144 → cholesky+inv 39,146,837 (0.0535% B).
        # ⚠️ ЗАХИСТ: при `n_pairs < width` вибіркова `cov` ВИРОДЖЕНА і Холецький
        #    падає, а `eigh` із підлогою 1e-8 — ні. Дрібні мережі валідатора
        #    саме такі (`_MIN_PAIRS`=128 < 256), тож там лишаємо старий шлях.
        if n_pairs > width:
            whiten = fnp.linalg.inv(fnp.linalg.cholesky(cov)).T
        else:
            evals, evecs = fnp.linalg.eigh(cov)
            inv_sqrt = 1.0 / fnp.sqrt(fnp.maximum(evals, 1e-8))
            whiten = fnp.matmul(evecs * inv_sqrt, evecs.T)

        denom = float(2 * n_pairs)
        zrow = fnp.zeros(width, dtype=fnp.float32)
        out = []

        # ⚠️ дрібні мережі валідатора: замикання не глибше, ніж є шарів
        ksig = _KSIG if _KSIG <= depth - 1 else depth - 1
        if ksig < 0:
            ksig = 0
        # 🔑 ГЛИБОКЕ замикання: ітеруємо крізь УСІ `depth` шарів (kdeep=depth),
        #    але λ-родини беруть лише шари 1..ksig — рівно як у sub87.
        s_cl, m_cl, q_cl, P_cl, m_deep, a_cl, b_cl = _closure_parts(
            w_cut, ksig, width, kdeep=depth)

        w0 = fnp.matmul(whiten, w_cut[0])
        # 🔑 ТА САМА АНТИТЕТИКА В ШАРІ 0: [z; −z] @ w0 = [y; −y], а relu від цього
        #    = [relu(y); relu(−y)] — БІТ У БІТ (заперечення у fp точне). Матмул
        #    робиться на n рядках замість 2n. Ще ≈1.9% флопів.
        y = _mm(z, w0)
        x = fnp.concatenate([fnp.maximum(y, 0.0), fnp.maximum(-y, 0.0)], axis=0)
        out.append(zrow if depth > 1 else fnp.sum(x, axis=0) / denom)

        sg0 = fnp.sqrt(fnp.maximum(fnp.sum(w_cut[0] * w_cut[0], axis=0), 1e-30))
        v = fnp.sum(x, axis=0) / denom - sg0 * _INV_SQRT_2PI

        for i in range(1, depth):
            p = _mm(x, w_cut[i])
            gate = fnp.sum((p[:_GATE_N] > 0.0).astype(p.dtype), axis=0) * _INV_GATE
            v = fnp.matmul(v, w_cut[i]) * gate
            if i <= ksig:
                # 🔑 δs = ŝ − s_замик. Обидва в тих самих одиницях, різниця мала —
                #    саме тому λ підганяється, а не ставиться в одиницю.
                p2 = p * p
                mh = fnp.sum(p, axis=0) / denom
                e2 = fnp.sum(p2, axis=0) / denom
                sh2 = fnp.maximum(e2 - mh * mh, 1e-30)
                sh = fnp.sqrt(sh2)
                # 🔑 sub93: ВИБІРКОВІ κ₃,κ₄ передактивації того ж проходу.
                #    Ціна — два множення на елемент і дві редукції (≈0.5% F),
                #    матмулів НЕ додає. Дають локальну поправку до `q`:
                #        Δq = (γ₁/3)·s²φ − (γ₂/12)·s²tφ,  γ₁=κ₃/ŝ³, γ₂=κ₄/ŝ⁴
                #    Опори `s²φ`, `s²tφ` — із ЗАМИКАННЯ (детерміновані), а `γ` —
                #    з вибірки: так вони корелюють із шумом самої ознаки, і це
                #    вимірно КРАЩЕ за істинні γ (×1.0054 проти ×1.0040).
                #    🚨 Поправка входить ЛИШЕ в ознаку, а НЕ в рекурсію `C`:
                #    у рекурсії та сама поправка дає ×0.875 (`side66/edgeksig.py`).
                e3 = fnp.sum(p2 * p, axis=0) / denom
                e4 = fnp.sum(p2 * p2, axis=0) / denom
                mh2 = mh * mh
                k3 = e3 - 3.0 * mh * e2 + 2.0 * (mh2 * mh)
                k4 = (e4 - 4.0 * mh * e3 + 6.0 * mh2 * e2
                      - 3.0 * (mh2 * mh2) - 3.0 * (sh2 * sh2))
                dq = ((k3 / (sh2 * sh)) * (_C3 * a_cl[i - 1])
                      - (k4 / (sh2 * sh2)) * (_C4 * b_cl[i - 1]))
                x = fnp.maximum(p, 0.0)
                xm = fnp.sum(x, axis=0) / denom
                xq = fnp.sum(x * x, axis=0) / denom
                v = (v + _LAM_SCALE * (
                     (_LAM_S[i - 1] * _phi(mh / sh)) * (sh - s_cl[i - 1])
                     + _LAM_A[i - 1] * (xm - m_cl[i - 1])
                     + _LAM_Q[i - 1] * ((xq - q_cl[i - 1]) - dq)
                     + _LAM_G[i - 1] * (gate - P_cl[i - 1])))
            else:
                x = fnp.maximum(p, 0.0)
            out.append(fnp.sum(x, axis=0) / denom if i == depth - 1 else zrow)

        ours = out[-1] - v
        # 🆕 С100 (ІДЕЯ ЮЗЕРА: «лос, схожа на кореляцію, але не кореляція»).
        #    Ціль після калібрування масштабу є ТОЧНО косинусною:
        #        min_a ‖a·m − T‖² = ‖T‖²·(1 − cos²(m,T))
        #    ⟹ масштаб — вільний параметр, і тримати його ОДНІЄЮ константою на
        #    всі мережі було втратою. `a_i` фітується проти ВЛАСНОЇ МК-оцінки
        #    (істина не потрібна): один скаляр по 256 числах ⟹ шум усереднюється.
        #    `[ЗМІРЯНО sig100, 50 мереж]` оракул ×1.2525, з реальним шумом МК
        #    ×1.2519 — втрата від шуму 0.05%. Ціна ~512 операцій.
        #    ⚠️ СТИСНЕННЯ `_A_SHRINK`: закон «оптимальна поправка СТИСНЕНА, а не
        #    точна» (С99) — при 1.0 беремо a_i повністю, при 0.0 стару константу.
        _num = fnp.sum(out[-1] * m_deep)
        _den = fnp.sum(m_deep * m_deep)
        _ai = _num / fnp.maximum(_den, 1e-30)
        _a = (1.0 - _A_SHRINK) * (1.0 + _ALPHA) + _A_SHRINK * _ai
        out[-1] = ours + _W_BLEND * (_a * m_deep - ours)
        return fnp.stack(out, axis=0)
