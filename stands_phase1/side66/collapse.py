"""ЧИ КОЛАПСУЄ РОЗПОДІЛ АКТИВАЦІЙ ДО МАЛОГО РАНГУ? (гейт до «ваг досить»)

Ідея юзера: відповідь — ДЕТЕРМІНОВАНА функція ваг, семплінг лише чисельно
обчислює відоме. Бюджету маємо ≈130 000 флопів НА КОЖНУ ВАГУ. Замикання вже
рахує з ваг (2.2% флопів, точність 0.9%), карта (K,ε) вимагає 0.02%.

🚨 ВІДОМА СТІНА: замикання — ТОЧКА БАЛАНСУ (похибки `m` і `C` в протилежні боки),
тож локальні поправки до Мелера K=2 закрито стелею 1.111×. АЛЕ це вирок про
ПОПРАВКИ, а не про ІНШИЙ спосіб рахувати з ваг.

🎯 ПІДКАЗКА З НАШИХ ЖЕ ДАНИХ: PR-ранг активацій падає 161.6 → 2.5, `cos(m,u₁)=0.978`.
Якщо на глибині розподіл справді майже ДВОВИМІРНИЙ, гаусове припущення там взагалі
не потрібне: 2-вимірний інтеграл рахується ТОЧНО і майже задарма. Замикання тягне
256×256 коваріацію з наближенням — а може досить тягнути ФОРМУ вздовж 1–2 осей.

МІРЯЄМО ПО ШАРАХ:
  PR — ефективний ранг ЦЕНТРОВАНОЇ коваріації доактивацій, (Σλ)²/Σλ²;
  частку дисперсії в топ-1 / топ-2 / топ-8 напрямках;
  надлишковий ексцес уздовж топ-1 (наскільки той напрямок НЕгаусів);
  ексцес окремої координати (це те, що прямо зміщує `E[ReLU]`).

📣 ПЕРЕДБАЧЕНО: PR падає до одиниць, топ-1 бере >70% дисперсії на шарах 25+.
🟢 ЖИВЕ, якщо на шарах 25–31 топ-2 бере ≥85% дисперсії ⟹ низькорангове ТОЧНЕ
   протягування форми стає обчислювально тривіальним і закриває головне
   наближення замикання.
⛔ МЕРТВО, якщо дисперсія лишається розмазаною: тоді «інший спосіб» вимагає
   повного 256-вимірного розподілу, і ми знову там, де були.
"""
import sys

import numpy as np
import torch

DEV = sys.argv[1] if len(sys.argv) > 1 else 'cuda:3'
NETS = int(sys.argv[2]) if len(sys.argv) > 2 else 6
NS = int(sys.argv[3]) if len(sys.argv) > 3 else 8192
W_ = 256

WZ = np.load('/mnt/win_d/llm/White-Box/arena60/fs_w.npy', mmap_mode='r')
print(__doc__.split('📣')[1], flush=True)

acc = {}
for n in range(NETS):
    W = [torch.tensor(np.asarray(WZ[n][k], np.float32), device=DEV)
         for k in range(32)]
    g = torch.Generator(device=DEV).manual_seed(41_000 + 13 * n)
    with torch.no_grad():
        h = torch.randn(NS, W_, device=DEV, generator=g)
        for L in range(32):
            p = (h @ W[L]).double()
            pc = p - p.mean(0, keepdim=True)
            C = (pc.T @ pc) / (NS - 1)
            ev = torch.linalg.eigvalsh(C).clamp_min(0)
            tot = float(ev.sum())
            pr = float(tot ** 2 / (ev * ev).sum())
            ev = torch.flip(ev, [0])
            t1 = float(ev[0]) / tot
            t2 = float(ev[:2].sum()) / tot
            t8 = float(ev[:8].sum()) / tot
            # надлишковий ексцес уздовж топ-1 напрямку
            _, V = torch.linalg.eigh(C)
            u1 = V[:, -1]
            proj = pc @ u1
            k1 = float((proj ** 4).mean() / (proj ** 2).mean() ** 2 - 3.0)
            # ексцес ОКРЕМОЇ координати — те, що прямо зміщує E[ReLU]
            kc = float(((pc ** 4).mean(0) / (pc ** 2).mean(0) ** 2 - 3.0).mean())
            acc.setdefault(L, []).append((pr, t1, t2, t8, k1, kc))
            h = torch.relu(p).float()
    del W
    torch.cuda.empty_cache()
    print(f'  … мережа {n+1}/{NETS}', flush=True)

print(f'\n{NETS} мереж × {NS} семплів\n')
print(f'{"шар":>4s} {"PR-ранг":>9s} {"топ-1":>8s} {"топ-2":>8s} {"топ-8":>8s} '
      f'{"ексц.топ1":>10s} {"ексц.коорд":>11s}')
print('-' * 62)
for L in range(32):
    a = np.array(acc[L]).mean(0)
    star = ' <<<' if L >= 25 else ''
    print(f'{L:4d} {a[0]:9.2f} {a[1]:7.1%} {a[2]:7.1%} {a[3]:7.1%} '
          f'{a[4]:+10.3f} {a[5]:+11.3f}{star}')
tail = np.array([np.array(acc[L]).mean(0) for L in range(25, 32)])
print(f'\nшари 25–31: PR {tail[:,0].mean():.2f} · топ-1 {tail[:,1].mean():.1%} · '
      f'топ-2 {tail[:,2].mean():.1%} · топ-8 {tail[:,3].mean():.1%}')
print(f'            ексцес топ-1 {tail[:,4].mean():+.3f} · '
      f'координати {tail[:,5].mean():+.3f}  (гаус = 0)')
ok = tail[:, 2].mean() >= 0.85
print(f'\n🔑 ВИРОК: {"🟢 ЖИВЕ" if ok else "⛔ МЕРТВО"} '
      f'(гейт: топ-2 ≥85% на шарах 25–31; вийшло {tail[:,2].mean():.1%})')
print('📊 БАЛ: 1.954e-07 — вимір структурний')
