"""ПЕРЕВІРКА ПРИЛАДУ: чи не занижував `infoscan` саме бінову колонку? (С82)

## ЗВІДКИ ПИТАННЯ
Юзер: «не рубай, а спершу перевір код, може ти допустив помилку». Перечитав
`score()` вручну і знайшов АСИМЕТРІЮ НЕ НА НАШУ КОРИСТЬ:

  бін-краї рахуються ГЛОБАЛЬНО по всіх мережах, а масштаб μ-якоря в мереж
  різний. Точки «широкої» мережі падають у крайні біни, де функція оцінена
  переважно по «вузьких» ⟹ бінову це РОЗМИВАЄ, а пряму — ні (вона просто
  продовжується за межі даних).

Тобто вирок «нелінійності нема» міг бути артефактом приладу, а не фактом.

## ЩО РОБИТЬ ЦЕЙ ФАЙЛ
Читає збережені `infoscan_data.npz` (перегін не потрібен) і додає режими,
де і ознака, і ціль переведені в ОДИНИЦІ МЕРЕЖІ:
    `g` фітується на `(x/σₓ, e/σₓ)`, а прогноз повертається як `σₓ·g(x/σₓ)`,
де `σₓ` — розкид ознаки В ЦІЙ мережі (доступний і в сабміті — це власні дані).
Тоді бінова ловить ФОРМУ залежності, вільну від масштабу мережі.

## РЕЖИМИ
  `lin`  / `bin`   — як було (глобальні одиниці)
  `linz` / `binz`  — нормовані по мережі
  ⛔`binz-перест.` · ⛔`binz-чужа` — ті самі два контролі
  🚨пломба потужності: `a³` і `∛a` — бінова МУСИТЬ дати те саме, що на `a`

## 🎯 ЧОГО ЧЕКАТИ
Якщо `binz` ≫ `linz`, а `bin` ≈ `lin` — прилад справді занижував, і сигнал є.
Якщо `binz` ≈ `linz` теж — нелінійності нема насправді.

Запуск: /mnt/win_d/llm/White-Box/torch_venv/bin/python side66/infoscan_z.py
"""
import numpy as np

D = np.load('/mnt/win_d/llm/White-Box/arena62/logs/infoscan_data.npz')
X, e1, e2 = D['X'].astype(np.float64), D['e1'], D['e2']
net = D['net']
NETS, NF = int(net.max()) + 1, X.shape[1]
NBIN = 40
LAYERS = (0, 1, 3, 7, 15, 23, 30)
NAMES = ([f'σ-ознака шару {l+1}' for l in LAYERS]
         + [f'μ-якір шару {l+1}' for l in LAYERS]
         + ['прогноз сабміту', 's_замик виходу', 'm_замик виходу',
            '🚨пломба: (μ-якір 24)³', '🚨пломба: ∛(μ-якір 24)'])
print(__doc__.split('## 🎯')[1].split('Запуск')[0], flush=True)
print(f'точок {len(e1)} · мереж {NETS} · ознак {NF}')

# 🔑 масштаб ознаки В КОЖНІЙ мережі (у сабміті теж доступний — це власні дані)
SIG = np.ones((NETS, NF))
for n in range(NETS):
    m = net == n
    SIG[n] = X[m].std(0)
SIG = np.maximum(SIG, 1e-300)
# 🔑 масштаб ЦІЛІ в мережі — один на мережу (беремо розкид прогнозу сабміту,
#    колонка 14; у сабміті доступний так само задарма)
SIGY = np.maximum(SIG[:, 14], 1e-300)


def run(x, a1, a2, mode, sig=None):
    """`sig` — масштаб ознаки по мережах; якщо заданий, працюємо в одиницях мережі."""
    # 🚨 ПОПРАВКА: перша версія ділила ЦІЛЬ на масштаб ОЗНАКИ. Для `a³` це інші
    #    одиниці ⟹ пломба інваріантності провалилась (5.68% замість 8.69%) —
    #    і провалилась вона на МОЄМУ режимі, а не на приладі. Правильно:
    #    ОЗНАКУ нормуємо на її власний розкид (щоб біни збігалися між мережами),
    #    ЦІЛЬ — на масштаб МЕРЕЖІ (спільний для всіх ознак, тож монотонна
    #    заміна ознаки його не чіпає). 🎓 ПЛОМБА ЗЛОВИЛА ХИБУ В САМІЙ ПЕРЕВІРЦІ.
    if sig is None:
        xx, s = x, np.ones_like(x)
    else:
        xx, s = x / sig[net], SIGY[net]
    ee = 0.5 * (a1 + a2) / s
    base = float(np.mean(a1 * a2))
    q = np.quantile(xx, np.linspace(0, 1, NBIN + 1)[1:-1])
    b = np.searchsorted(q, xx)
    fit = np.zeros_like(ee)
    for n in range(NETS):
        te, tr = net == n, net != n
        if mode == 'bin':
            sm = np.bincount(b[tr], ee[tr], NBIN)
            c = np.bincount(b[tr], None, NBIN)
            fit[te] = np.where(c > 30, sm / np.maximum(c, 1), 0.0)[b[te]]
        else:
            xt, et = xx[tr], ee[tr]
            v = xt.var()
            k = 0.0 if v < 1e-300 else float(
                ((xt - xt.mean()) * (et - et.mean())).mean() / v)
            fit[te] = et.mean() + k * (xx[te] - xt.mean())
    fit = fit * s
    return 1.0 - float(np.mean((a1 - fit) * (a2 - fit))) / base


rng = np.random.default_rng(4242)
perm = rng.permutation(len(e1))
off, shift = 0, np.zeros(len(e1), dtype=np.int64)
for n in range(NETS):
    k = int((net == n).sum())
    shift[off:off + k] = (np.arange(k) + (off + k) % len(e1)) % len(e1)
    off += k

print(f'\n{"ознака":26s} {"лін.":>8s}{"бінова":>8s} │{"лінZ":>8s}{"біноваZ":>9s}'
      f'{"⛔перест":>9s}{"⛔чужа":>8s}')
print('─' * 78)
R = []
for j in range(NF):
    r = [100 * run(X[:, j], e1, e2, 'lin'),
         100 * run(X[:, j], e1, e2, 'bin'),
         100 * run(X[:, j], e1, e2, 'lin', SIG[:, j]),
         100 * run(X[:, j], e1, e2, 'bin', SIG[:, j]),
         100 * run(X[perm, j], e1, e2, 'bin', SIG[:, j]),
         100 * run(X[shift, j], e1, e2, 'bin', SIG[:, j])]
    R.append(r)
    print(f'{NAMES[j]:26s} {r[0]:7.2f}%{r[1]:7.2f}% │{r[2]:7.2f}%{r[3]:8.2f}%'
          f'{r[4]:8.2f}%{r[5]:7.2f}%')

JA = 12
print(f'\n⛔ ПЛОМБА ПОТУЖНОСТІ (бінова інваріантна до монотонної заміни ознаки)')
print(f'   сирий μ-якір 24        біноваZ {R[JA][3]:6.2f}%  лінZ {R[JA][2]:6.2f}%')
for j in (NF - 2, NF - 1):
    print(f'   {NAMES[j]:22s} біноваZ {R[j][3]:6.2f}%  лінZ {R[j][2]:6.2f}%')
# 🎓 У Z-РЕЖИМІ ТОЧНА ІНВАРІАНТНІСТЬ НЕМОЖЛИВА В ПРИНЦИПІ: нормування ознаки
#    на її ВЛАСНИЙ розкид саме залежить від перетворення (`σ(a³)` не пов'язане
#    з `σ(a)` однаково в усіх мереж), тож упорядкування МІЖ мережами
#    зсувається. Строгу пломбу дає лише ГЛОБАЛЬНИЙ режим, де бін-краї
#    квантильні ⟹ інваріантні до будь-якої монотонної заміни точно.
ok = all(abs(R[j][1] - R[JA][1]) < 0.05 for j in (NF - 2, NF - 1)) \
    and R[NF - 2][0] < R[JA][0] - 1.0
print(f'   глобальний режим (СТРОГА пломба): {R[JA][1]:.2f}% · '
      f'{R[NF-2][1]:.2f}% · {R[NF-1][1]:.2f}%  при лінійних '
      f'{R[JA][0]:.2f}% · {R[NF-2][0]:.2f}% · {R[NF-1][0]:.2f}%')
print(f'   ⟹ {"✅ ПРИЛАД ЗРЯЧИЙ" if ok else "🚨 ПРИЛАД СЛІПИЙ — ВИРОК НЕДІЙСНИЙ"}'
      ' (Z-режим лише орієнтовний — там інваріантність принципово неточна)')

# 🚨 ТРЕТЯ ПІДОЗРА: точки НЕ незалежні — нейрони всередині жеребу корельовані
#    (ефективних напрямків промаху ~2.9 із 256 ⟹ ефективно ≈1000 незалежних
#    точок, а не 98304). Тоді 40 бінів = ~25 незалежних на бін, і бінова шумна
#    на відкладеній мережі. Це ЗНОВУ проти неї. Свіпимо число бінів.
print('\n🔍 СВІП ЧИСЛА БІНІВ (мало бінів = менше шуму, більше зміщення)')
print(f'{"ознака":26s} {"лінZ":>8s}' + ''.join(f'{f"бін={k}":>9s}'
                                               for k in (6, 10, 16, 25, 40)))
for j in (JA, JA + 1, 8, 10):
    row = f'{NAMES[j]:26s} {R[j][2]:7.2f}%'
    for k in (6, 10, 16, 25, 40):
        NBIN = k
        row += f'{100*run(X[:, j], e1, e2, "bin", SIG[:, j]):8.2f}%'
    print(row)
NBIN = 40

NR = NF - 2
gz = max(R[j][3] - max(R[j][2], R[j][4], R[j][5]) for j in range(NR))
jz = max(range(NR), key=lambda j: R[j][3] - max(R[j][2], R[j][4], R[j][5]))
g0 = max(R[j][1] - R[j][0] for j in range(NR))
print(f'\n⚖️ надлишок бінової над лінійною: ГЛОБАЛЬНІ одиниці {g0:.2f}%  ·  '
      f'ОДИНИЦІ МЕРЕЖІ {gz:.2f}%  ({NAMES[jz]})')
print(f'📊 БАЛ 1.954e-07 ⟹ якби надлишок брався весь: '
      f'{1.954e-07*(1-max(gz,0)/100):.4e}')
