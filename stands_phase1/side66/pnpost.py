"""ПОСТАНАЛІЗ `perneuron.npz`: ЧИ `γ` УНІВЕРСАЛЬНИЙ ПО МЕРЕЖАХ. (С86)

Вимір A показав, що понейронних 4 моментів вистачає (×12 локальної точності).
Вимір B показав, що діагональна рекурсія `κ₄` дає лише ~3% істини ⟹ ВЕСТИ їх
рекурсивно не можна. Лишається третій шлях, який B не перевіряв:

🔑 ЯКЩО `γ₃`,`γ₄` НА ШАРІ ОДНАКОВІ ДЛЯ ВСІХ МЕРЕЖ — їх узагалі не треба
   обчислювати. Достатньо ЗАТАБУЛЮВАТИ 32 пари чисел як константи. Ціна нуль.

Це те саме питання, що вирішило долю `_ALPHA`: там один скаляр на всю мережу
виявився переносимим між мережами (LOO 0.9645% → 0.6013%).

⛔ПЛОМБА: розкид ПО МЕРЕЖАХ порівнюється з розкидом ПО ШАРАХ. Якщо міжмережевий
   розкид не набагато менший — універсальності немає, і табулювання не працює.
"""
import numpy as np

D = np.load('/mnt/win_d/llm/White-Box/arena62/logs/perneuron.npz')
g4, g3r, tabs = D['g4'], D['g3'], D['tabs']
nets, L = g4.shape
print(f'{nets} мереж × {L} шарів\n')

print('📊 УНІВЕРСАЛЬНІСТЬ ПО МЕРЕЖАХ (шар за шаром)')
print(f'{"шар":>4s} {"⟨γ₄⟩":>9s} {"std по мер.":>12s} {"варіація":>10s} '
      f'{"RMSγ₃":>9s} {"std по мер.":>12s} {"варіація":>10s} {"|t|":>7s} {"std":>8s}')
print('─' * 90)
for i in [0, 1, 3, 5, 7, 11, 15, 19, 23, 27, 31]:
    a, b, c = g4[:, i], g3r[:, i], tabs[:, i]
    print(f'{i+1:4d} {a.mean():9.4f} {a.std():12.5f} {a.std()/max(abs(a.mean()),1e-12):10.4f} '
          f'{b.mean():9.4f} {b.std():12.5f} {b.std()/max(abs(b.mean()),1e-12):10.4f} '
          f'{c.mean():7.3f} {c.std():8.4f}')
print('─' * 90)

sl = slice(4, 32)
for nm, arr in (('γ₄', g4), ('RMS γ₃', g3r), ('|t|', tabs)):
    within = arr[:, sl].std(0).mean()        # розкид ПО МЕРЕЖАХ у межах шару
    across = arr[:, sl].mean(0).std()         # розкид ПО ШАРАХ
    print(f'{nm:>8s}: розкид по МЕРЕЖАХ {within:.5f} · по ШАРАХ {across:.5f} '
          f'⟹ відношення {across/max(within,1e-12):.1f}×')
print('\n🎯 відношення ≫1 ⟹ шар визначає майже все, мережа майже нічого')
print('   ⟹ 32 пари констант замінюють обчислення. Відношення ~1 ⟹ не працює.')
