import flopscope as flops                                     # noqa: E402
import flopscope.numpy as fnp                                 # noqa: E402

W = 256
D = 32
B = 2.72e11


def carry(r, it):
    """Один ПОВНИЙ шар трьохмоментного замикання з ранг-r κ₃."""
    w = fnp.ones((W, W), dtype=fnp.float32)
    A = fnp.ones((r, W), dtype=fnp.float32)          # моди κ₃
    c = fnp.ones(r, dtype=fnp.float32)               # ваги мод
    m = fnp.ones(W, dtype=fnp.float32)
    C = fnp.ones((W, W), dtype=fnp.float32)

    # (A) перенесення мод: A ← A·W   (r матвекторів, одним матмулом)
    A = fnp.matmul(A, w)
    # (B) застосування: внесок κ₃ у m і в діагональ/позадіагональ C
    s = fnp.sqrt(fnp.maximum(fnp.diagonal(C), 1e-20))
    t = m / s
    ph = fnp.exp(-0.5 * t * t)
    g3 = fnp.matmul(c, A * A * A) / (s * s * s)      # γ₃ понейронно з рангу
    m = m + (s * ph) * g3 * (1.0 / 6.0)
    # позадіагональ: ранг-r внесок у Cov через ермітів коефіцієнт a₂
    P = A / s                                        # (r, W)
    C = C + fnp.matmul((P * c[:, None]).T, P) * fnp.outer(ph, ph)
    # (C) перепроєкція після ReLU: степеневий метод `it` ітерацій
    for _ in range(it):
        A = fnp.matmul(fnp.matmul(A, C), fnp.eye(W, dtype=fnp.float32))
        A = A / fnp.maximum(fnp.sqrt(fnp.sum(A * A, axis=1))[:, None], 1e-20)
    return m, C, A


