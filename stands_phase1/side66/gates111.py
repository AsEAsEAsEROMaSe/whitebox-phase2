# С111: спостереження ЮЗЕРА «чим глибше тим менше ваг активуються, але все одно
# активуються дуже рідко». Міряємо ПОЛЯРИЗАЦІЮ затворів по глибині.
# ПЕРЕДБАЧЕННЯ: середня частка активних ~0.49 СТАЛА (запис корпусу), але
# число «завжди відкритих» (p>0.95) і «завжди закритих" (p<0.05) РОСТЕ.
# ПРАКТИЧНИЙ ВИХІД: злиття лінійних шарів окупається при |A| > 128 з 256.
import numpy as np
W=np.load('/mnt/win_d/llm/White-Box/arena60/fs_w.npy',mmap_mode='r')
rng=np.random.default_rng(31337); NET=8; NS=16384
P=np.zeros((32,256))
for n in range(NET):
    Wn=[np.array(W[n,l],dtype=np.float64) for l in range(32)]
    acc=np.zeros((32,256)); h=None
    for i in range(0,NS,4096):
        z=rng.standard_normal((4096,256)); h=z
        for l in range(32):
            p=h@Wn[l]; acc[l]+= (p>0).sum(0); h=np.maximum(p,0.0)
    P+=acc/NS
P/=NET
print(f"{'шар':>4}{'сер. частка':>13}{'p>0.95':>9}{'p>0.99':>9}{'p<0.05':>9}{'p<0.01':>9}{'|A| разом':>11}{'перемик.':>10}")
for l in [0,1,2,4,8,12,16,20,24,28,30,31]:
    p=P[l]
    a95=(p>0.95).sum(); a99=(p>0.99).sum(); d05=(p<0.05).sum(); d01=(p<0.01).sum()
    sw=((p>=0.05)&(p<=0.95)).sum()
    print(f"{l:>4}{p.mean():>13.4f}{a95:>9}{a99:>9}{d05:>9}{d01:>9}{a95+d05:>11}{sw:>10}")
print()
print("ЗЛИТТЯ ЛІНІЙНИХ ШАРІВ окупається при |завжди відкритих| > 128 з 256:")
for l in range(32):
    a=(P[l]>0.95).sum()
    if a>128: print(f"  шар {l}: {a} завжди відкритих ⟹ ОКУПАЄТЬСЯ")
print(f"  максимум по всіх шарах: {max((P[l]>0.95).sum() for l in range(32))}")
print()
print("СУМАРНО по мережі (частка від 32×256 = 8192 нейронів):")
tot=P.size
print(f"  завжди відкриті (p>0.95): {(P>0.95).sum():>5} = {(P>0.95).sum()/tot*100:5.1f}%")
print(f"  завжди закриті  (p<0.05): {(P<0.05).sum():>5} = {(P<0.05).sum()/tot*100:5.1f}%")
print(f"  реально перемикні:        {((P>=0.05)&(P<=0.95)).sum():>5} = {((P>=0.05)&(P<=0.95)).sum()/tot*100:5.1f}%")
